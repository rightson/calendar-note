const assert=require('node:assert/strict');
const core=require('./event-core.js');
const event={source:'local',uid:'local-42',title:'Yesterday [Discussion]|#Plan',start:'2026-10-22T10:00:00+08:00',end:'2026-10-22T11:00:00+08:00'};
assert.equal(core.dailyPath('[Daily Notes]/YYYY/MM/DD',event,'en'),'Daily Notes/2026/10/22.md');
assert.equal(core.stableKey({...event,start:'2026-10-23T12:00:00+08:00'}),core.stableKey(event));
const imported={...event,source:'work',originalStart:event.start};
assert.equal(core.stableKey({...imported,start:'2026-10-23T12:00:00+08:00'}),core.stableKey(imported));
let diary='# 2026-10-22\n\n## Event\n\n- Existing event\n\n### Ideas\nPreserved content\n\n## Journal\n\nThoughts for today.\n';
const added=core.upsertDailyEvent(diary,event,'Calendar Notes/Yesterday.md');
assert.ok(added.content.includes('- Existing event'));
assert.ok(added.content.includes('### Ideas\nPreserved content'));
assert.ok(added.content.includes('## Journal\n\nThoughts for today.\n'));
assert.ok(added.content.indexOf(added.bullet)<added.content.indexOf('## Journal'));
assert.equal(added.bullet,'- 10:00–11:00 [[Calendar Notes/Yesterday|Yesterday Discussion Plan]]');
assert.equal(core.upsertDailyEvent(added.content,event,'Calendar Notes/Yesterday.md',added.bullet).content,added.content);
assert.equal(core.upsertDailyEvent(added.content,event,'Calendar Notes/Yesterday.md').content,added.content);
const movedTime={...event,start:'2026-10-22T10:15:00+08:00'};
const updated=core.upsertDailyEvent(added.content,movedTime,'Calendar Notes/Yesterday.md',added.bullet);
assert.ok(!updated.content.includes(added.bullet));assert.ok(updated.content.includes('- 10:15–11:00'));
const removed=core.removeTrackedBullet(updated.content,updated.bullet);
assert.ok(!removed.includes('Calendar Notes/Yesterday'));assert.ok(removed.includes('## Journal\n\nThoughts for today.'));
const noSection='# Day\n\nUnrelated paragraph.\n';
assert.ok(core.upsertDailyEvent(noSection,event,'e.md').content.startsWith(noSection));
assert.ok(core.upsertDailyEvent(noSection,event,'e.md').content.includes('## Event\n'));
const fenced='# Day\n\n```md\n## Event\n```\n\n## Journal\nKeep.\n';
const fencedResult=core.upsertDailyEvent(fenced,event,'e.md').content;
assert.ok(fencedResult.startsWith(fenced));assert.equal(core.headings(fencedResult).filter(h=>h.title==='Event').length,1);
const withFence='# Day\n## Event\n\n~~~md\n## Fake\n~~~\n\n# Next\nUntouched\n';
const fenceAppend=core.upsertDailyEvent(withFence,event,'e.md');assert.ok(fenceAppend.content.indexOf(fenceAppend.bullet)<fenceAppend.content.indexOf('# Next'));
const body='# My note\n\nPreserved body\n';
let note=core.updateFrontmatter('---\ntags:\n  - project\ncustom: keep\nstart: "old"\n---\n'+body,event);
assert.ok(note.endsWith(body));assert.ok(note.includes('tags:\n  - project\ncustom: keep'));
assert.equal((note.match(/^start:/gm)||[]).length,1);assert.equal(core.splitFrontmatter(core.updateFrontmatter(body,event)).yaml.split('\n').length,3);
const resized=core.resizeInterval(event,'start',22);assert.equal(resized.start,'2026-10-22T10:15:00+08:00');assert.equal(resized.end,event.end);
assert.equal(core.resizeInterval(event,'end',38).end,'2026-10-22T11:45:00+08:00');
assert.throws(()=>core.resizeInterval(event,'start',60));assert.throws(()=>core.validateInterval(event.start,'2026-10-22T10:00:00+08:00'));assert.throws(()=>core.validateInterval(event.start,'2026-10-23T01:00:00+08:00'));
const layout=core.layoutOverlaps([{id:'a',start:600,end:660},{id:'b',start:615,end:675},{id:'c',start:630,end:690},{id:'d',start:690,end:720}]);
assert.equal(new Set(layout.filter(e=>e.id!=='d').map(e=>e.column)).size,3);assert.ok(layout.filter(e=>e.id!=='d').every(e=>e.columns===3));assert.equal(layout.find(e=>e.id==='d').columns,1);
assert.equal(core.isEventVisible(event,[],true),true);
assert.equal(core.isEventVisible(imported,[],true),false);
assert.equal(core.isEventVisible(imported,[{id:'work',url:'',enabled:true}],true),false);
assert.equal(core.isEventVisible(event,[],false),false);
console.log('Event core checks passed: event-date Daily Notes, section boundaries/fences/dedup, preserved Markdown/YAML, stable identity, generic overlaps and snapped resizing.');

const yamlDiary='---\nmemo: |\n  ## Event\n---\n# Day\n\n## Journal\nKeep.\n';
const yamlAdded=core.upsertDailyEvent(yamlDiary,event,'e.md');
assert.ok(yamlAdded.content.startsWith(yamlDiary));assert.equal(core.headings(yamlAdded.content).filter(h=>h.title==='Event').length,1);
const duplicateElsewhere='## Event\n\n```md\n'+added.bullet+'\n```\n\n## Journal\n'+added.bullet+'\n';
const scoped=core.upsertDailyEvent(duplicateElsewhere,event,'Calendar Notes/Yesterday.md');
assert.equal(scoped.content.split(added.bullet).length-1,3);
const scopedRemoved=core.removeTrackedBullet(scoped.content,added.bullet);
assert.equal(scopedRemoved.split(added.bullet).length-1,2);
assert.ok(scopedRemoved.includes('```md\n'+added.bullet+'\n```'));
assert.ok(scopedRemoved.endsWith('## Journal\n'+added.bullet+'\n'));
assert.equal(core.dailyBullet({...event,start:'2026-10-22T23:00:00+08:00',end:'2026-10-23T00:00:00+08:00'},'e.md'),'- 23:00–24:00 [[e|Yesterday Discussion Plan]]');
assert.equal(core.dailyBullet({...event,allDay:true},'e.md'),'- All day [[e|Yesterday Discussion Plan]]');
const path=require('./path-format.js').formatPath('[Notes]/{title}',{...event,calendar:'Local events',title:'Discussion [A] #Meeting ^id'},'zh-tw');
assert.equal(path,'Notes/Discussion A Meeting id.md');
assert.ok(core.dailyBullet({...event,title:'Discussion [A] #Meeting ^id'},path).includes('[[Notes/Discussion A Meeting id|'));
console.log('Additional safety checks passed: YAML/fence scope, wikilink-safe paths, optional sources and midnight/all-day links.');
