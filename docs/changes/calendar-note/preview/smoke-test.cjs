const assert = require('node:assert/strict');
const {formatPath, cleanSegment} = require('./path-format.js');
const e = {title:'Product strategy / Q4: Roadmap?',calendar:'Work / Team',uid:'event:42',start:'2026-10-23T10:00:00+08:00'};
assert.equal(formatPath('[Calendar Notes]/{title}', e, 'en'), 'Calendar Notes/Product strategy Q4 Roadmap.md');
assert.equal(formatPath('[Meetings]/YYYY/MM/DD/{title}', e, 'en'), 'Meetings/2026/10/23/Product strategy Q4 Roadmap.md');
assert.equal(formatPath('YYYY/MMMM/YYYY-MMM-DD/{title}', e, 'en'), '2026/October/2026-Oct-23/Product strategy Q4 Roadmap.md');
assert.equal(formatPath('[Notes]/{title}', {...e,title:'YYYY-MM-DD.md.md'}, 'en'), 'Notes/YYYY-MM-DD.md');
assert.equal(formatPath('[Notes]/{calendar}/{uid}',e,'en'),'Notes/Work Team/event 42.md');
assert.equal(cleanSegment('CON'), '_CON');
assert.equal(cleanSegment('...'), 'Untitled event');
for (const path of ['/absolute/{title}','C:/notes/{title}','../{title}','[Notes]/../{title}','[Notes]/{missing}']) assert.throws(()=>formatPath(path,e,'en'));
assert.throws(()=>formatPath('[Notes]/{title}',{...e,start:'not-a-date'},'en'));
console.log('Path smoke checks passed: literal text, Moment locales, event date, placeholder protection, sanitization, relative paths, reserved names and extension.');
assert.equal(formatPath('[Meetings]/GGGG/[W]WW/{title}',e,'en'),'Meetings/2026/W43/Product strategy Q4 Roadmap.md');
assert.equal(formatPath('YYYY/MMMM/{title}',e,'zh-tw'),'2026/\u5341\u6708/Product strategy Q4 Roadmap.md');
assert.equal(formatPath('[Notes]/{title}',{...e,title:'YYYY/MM/DD'},'en'),'Notes/YYYY MM DD.md');
assert.equal(formatPath('[Project {code}]/YYYY/MM/DD',e,'en'),'Project {code}/2026/10/23.md');
assert.equal(formatPath('\\Y/YYYY/{title}',e,'en'),'Y/2026/Product strategy Q4 Roadmap.md');
assert.equal(cleanSegment('\u0000\u0001  '),'Untitled event');
assert.equal(cleanSegment('NUL.txt'),'_NUL.txt');
const unicodeName=cleanSegment('🎉'.repeat(140));
assert.ok(new TextEncoder().encode(unicodeName).byteLength <= 200);
assert.ok(Array.from(unicodeName).every(c => !(c.codePointAt(0)>=0xd800 && c.codePointAt(0)<=0xdfff)));
assert.ok(new TextEncoder().encode(cleanSegment('\u6703'.repeat(140))).byteLength <= 200);
assert.equal(cleanSegment('\ud800'), 'Untitled event');
assert.equal(formatPath('[Notes]/{title}.md',{...e,title:'already.md'},'en'),'Notes/already.md');
console.log('Expanded Daily Notes compatibility checks passed.');
